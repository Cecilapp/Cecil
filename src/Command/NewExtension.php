declare(strict_types=1);

namespace Cecil\Command;

use Cecil\Exception\RuntimeException;
use Cecil\Util;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputArgument;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Input\InputOption;
use Symfony\Component\Console\Output\OutputInterface;

/**
 * NewExtension command.
 *
 * This command creates the skeleton of an extension class (generator, Twig extension, post-processor,
 * event subscriber or plugin) in the `extensions` directory, and displays the configuration to enable it.
 */
class NewExtension extends AbstractCommand
{
    /**
     * Extension types: sub-namespace, configuration key and class template.
     */
    public const array TYPES = [
        'generator' => [
            'subnamespace' => 'Generator',
            'key'          => 'pages.generators',
            'template'     => <<<'PHP'
                use Cecil\Collection\Page\Page;
                use Cecil\Collection\Page\Type;
                use Cecil\Generator\AbstractGenerator;

                class %class% extends AbstractGenerator
                {
                    public function generate(): void
                    {
                        $page = (new Page('%id%'))
                            ->setType(Type::PAGE)
                            ->setPath('%id%')
                            ->setBodyHtml('<p>Generated by %class%.</p>')
                            ->setVariable('title', '%class%');
                        $this->generatedPages->add($page);
                    }
                }
                PHP,
        ],
        'twig' => [
            'subnamespace' => 'Twig',
            'key'          => 'layouts.extensions',
            'template'     => <<<'PHP'
                use Cecil\Builder;
                use Twig\Extension\AbstractExtension;
                use Twig\TwigFilter;
                use Twig\TwigFunction;

                class %class% extends AbstractExtension
                {
                    public function __construct(protected Builder $builder)
                    {
                    }

                    public function getFilters(): array
                    {
                        return [
                            new TwigFilter('%id%', fn (string $value): string => $value),
                        ];
                    }

                    public function getFunctions(): array
                    {
                        return [
                            new TwigFunction('%id%', fn (): string => (string) $this->builder->getConfig()->get('title')),
                        ];
                    }
                }
                PHP,
        ],
        'postprocessor' => [
            'subnamespace' => 'PostProcessor',
            'key'          => 'output.postprocessors',
            'template'     => <<<'PHP'
                use Cecil\Collection\Page\Page;
                use Cecil\Renderer\PostProcessor\AbstractPostProcessor;

                class %class% extends AbstractPostProcessor
                {
                    public function process(Page $page, string $output, string $format): string
                    {
                        if ($format !== 'html') {
                            return $output;
                        }

                        // modify the HTML output here
                        return $output;
                    }
                }
                PHP,
        ],
        'subscriber' => [
            'subnamespace' => 'Subscriber',
            'key'          => 'extensions.subscribers',
            'template'     => <<<'PHP'
                use Cecil\Event\AbstractSubscriber;
                use Cecil\Event\BuildEvent;
                use Cecil\Event\BuildEvents;
                use Cecil\Event\PageRenderedEvent;

                class %class% extends AbstractSubscriber
                {
                    public static function getSubscribedEvents(): array
                    {
                        return [
                            BuildEvents::PAGE_RENDERED  => 'onPageRendered',
                            BuildEvents::BUILD_FINISHED => 'onBuildFinished',
                        ];
                    }

                    public function onPageRendered(PageRenderedEvent $event): void
                    {
                        // $event->setOutput($event->getOutput());
                    }

                    public function onBuildFinished(BuildEvent $event): void
                    {
                        $this->builder->getLogger()->info('%class%: build finished');
                    }
                }
                PHP,
        ],
        'plugin' => [
            'subnamespace' => '',
            'key'          => 'extensions.plugins',
            'template'     => <<<'PHP'
                use Cecil\Plugin\AbstractPlugin;
                use Cecil\Plugin\Registry;

                class %class% extends AbstractPlugin
                {
                    public function register(Registry $registry): void
                    {
                        $registry
                            ->config(['%id%' => []]);
                            // ->generator(Generator\MyGenerator::class, priority: 35)
                            // ->twigExtension(Twig\MyExtension::class)
                            // ->postProcessor(PostProcessor\MyPostProcessor::class)
                            // ->subscriber(Subscriber\MySubscriber::class)
                    }
                }
                PHP,
        ],
    ];

    /**
     * {@inheritdoc}
     */
    #[\Override]
    protected function configure()
    {
        $this
            ->setName('new:extension')
            ->setDescription('Creates a new extension')
            ->setDefinition([
                new InputArgument('path', InputArgument::OPTIONAL, 'Use the given path as working directory'),
                new InputOption('type', 't', InputOption::VALUE_REQUIRED, \sprintf('Extension type (%s)', implode(', ', array_keys(self::TYPES)))),
                new InputOption('name', null, InputOption::VALUE_REQUIRED, 'Extension class name (e.g.: "MyGenerator")'),
                new InputOption('namespace', null, InputOption::VALUE_REQUIRED, 'Root namespace of the extension (e.g.: "MySite")'),
                new InputOption('force', 'f', InputOption::VALUE_NONE, 'Override the file if already exist'),
            ])
            ->setHelp(
                <<<'EOF'
The <info>%command.name%</> command creates the skeleton of an extension class in the <comment>extensions</> directory,
and displays the configuration to enable it.
If you run this command without any options, it will ask you for the extension type, name and namespace.

  <info>%command.full_name%</>
  <info>%command.full_name% --type=generator --name=Database --namespace=MySite</>

Available types: <comment>generator</>, <comment>twig</>, <comment>postprocessor</>, <comment>subscriber</> and <comment>plugin</>.

To <comment>override</comment> an existing extension, run:

  <info>%command.full_name% --force</>
EOF
            );
    }

    /**
     * {@inheritdoc}
     *
     * @throws RuntimeException
     */
    #[\Override]
    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $type = (string) $input->getOption('type');
        $name = (string) $input->getOption('name');
        $namespace = (string) $input->getOption('namespace');
        $force = (bool) $input->getOption('force');

        $this->io->title('Create a new extension');
        // ask
        if ($type === '') {
            $type = (string) $this->io->choice('Which type of extension?', array_keys(self::TYPES), 'generator');
        }
        if (!isset(self::TYPES[$type])) {
            throw new RuntimeException(\sprintf('Unknown extension type "%s" (expected: %s).', $type, implode(', ', array_keys(self::TYPES))));
        }
        if ($name === '') {
            $name = (string) $this->io->ask('Give a class name for the extension:', 'My' . ucfirst(self::TYPES[$type]['subnamespace'] ?: 'Plugin'));
        }
        if ($namespace === '') {
            $namespace = (string) $this->io->ask('Give a root namespace for the extension:', 'MySite');
        }
        // validate
        $name = ucfirst(trim($name));
        $namespace = trim($namespace, '\\ ');
        if (!preg_match('/^[A-Za-z_][A-Za-z0-9_]*$/', $name)) {
            throw new RuntimeException(\sprintf('"%s" is not a valid class name.', $name));
        }
        if (!preg_match('/^[A-Za-z_][A-Za-z0-9_]*(\\\\[A-Za-z_][A-Za-z0-9_]*)*$/', $namespace)) {
            throw new RuntimeException(\sprintf('"%s" is not a valid namespace.', $namespace));
        }
        if ($namespace === 'Cecil' || str_starts_with($namespace, 'Cecil\\')) {
            throw new RuntimeException('The "Cecil" namespace is reserved: use your own namespace.');
        }
        $classNamespace = trim($namespace . '\\' . self::TYPES[$type]['subnamespace'], '\\');
        $fqcn = "$classNamespace\\$name";
        // define target path
        $fileRelativePath = Util::joinFile('extensions', str_replace('\\', DIRECTORY_SEPARATOR, $fqcn) . '.php');
        $filePath = Util::joinFile($this->getPath(), $fileRelativePath);
        // ask to override existing file?
        if (Util\File::getFS()->exists($filePath) && !$force) {
            $this->io->warning(\sprintf('The file "%s" already exists.', $fileRelativePath));
            if (!$this->io->confirm('Do you want to override it?', false)) {
                return Command::SUCCESS;
            }
        }
        // creates the class file
        Util\File::getFS()->dumpFile($filePath, $this->getContent($type, $classNamespace, $name));
        $this->io->success(\sprintf('Extension "%s" created at %s', $fqcn, $filePath));
        // configuration to enable it
        $this->io->text('Add it to your configuration:');
        $this->io->newLine();
        $this->io->text($this->getConfigSnippet(self::TYPES[$type]['key'], $name, $fqcn));
        $this->io->newLine();

        return Command::SUCCESS;
    }

    /**
     * Returns the content of the class file.
     */
    private function getContent(string $type, string $namespace, string $class): string
    {
        $template = str_replace(
            ['%class%', '%id%'],
            [$class, Util\Slugifier::slugify($class)],
            self::TYPES[$type]['template']
        );

        return "<?php\n\nnamespace $namespace;\n\n$template\n";
    }

    /**
     * Returns the YAML configuration snippet to enable the extension.
     *
     * @return list<string>
     */
    private function getConfigSnippet(string $key, string $name, string $class): array
    {
        $lines = [];
        $indent = 0;
        foreach (explode('.', $key) as $fragment) {
            $lines[] = str_repeat('  ', $indent++) . "$fragment:";
        }
        $lines[] = str_repeat('  ', $indent) . "$name: $class";

        return array_map(fn (string $line) => "  <comment>$line</>", $lines);
    }
}
